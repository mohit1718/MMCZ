export function QR({ text, size = 64 }) {
  const n = 25,
    r = rng(hash(text));
  let d = '';
  const fin = (x, y) => {
    d += `M${x} ${y}h7v7h-7zM${x + 1} ${y + 1}v5h5v-5zM${x + 2} ${y + 2}h3v3h-3z`;
  };
  for (let y = 0; y < n; y++)
    for (let x = 0; x < n; x++) {
      const inF = (x < 8 && y < 8) || (x > n - 9 && y < 8) || (x < 8 && y > n - 9);
      if (!inF && r() > 0.52) d += `M${x} ${y}h1v1h-1z`;
    }
  fin(0, 0);
  fin(n - 7, 0);
  fin(0, n - 7);
  return (
    <svg viewBox="-1 -1 27 27" width={size} height={size} role="img" aria-label={'Verification code for ' + text}>
      <rect x="-1" y="-1" width="27" height="27" fill="#fff" />
      <path d={d} fill="#0A1E45" fillRule="evenodd" />
    </svg>
  );
}

