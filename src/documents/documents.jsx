export function PdfJob({ db, job, onDone, toast }) {
  const ref = useRef(null);
  const c = db.cons[job.id];
  useEffect(() => {
    let dead = false;
    (async () => {
      try {
        const { jsPDF, html2canvas } = await loadPdfEngine();
        if (document.fonts && document.fonts.ready) await document.fonts.ready;
        await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
        const pdf = new jsPDF({
          unit: 'mm',
          format: 'a4',
        });
        const els = [...ref.current.querySelectorAll('.doc-sheet')];
        for (let i = 0; i < els.length; i++) {
          const cv = await html2canvas(els[i], {
            scale: 2,
            backgroundColor: '#ffffff',
            logging: false,
            useCORS: true,
          });
          const img = cv.toDataURL('image/jpeg', 0.92);
          let w = 210,
            h = (cv.height * 210) / cv.width;
          if (h > 297) {
            w = (w * 297) / h;
            h = 297;
          }
          if (i) pdf.addPage();
          pdf.addImage(img, 'JPEG', (210 - w) / 2, 0, w, h);
        }
        const blob = pdf.output('blob');
        await saveFile(job.name, blob);
        if (!dead) toast(`Document generated: ${job.name}`, 'ok');
      } catch (e) {
        const code = e && e.code;
        if (!dead)
          toast(
            code === 'declined'
              ? 'Download cancelled.'
              : code === 'rate_limited'
                ? 'A save prompt is already open. Finish it first.'
                : e.message || 'Could not generate the PDF.',
            code === 'declined' ? '' : 'bad',
          );
      } finally {
        if (!dead) onDone();
      }
    })();
    return () => {
      dead = true;
    };
  }, []);
  return (
    <div className="offscreen" ref={ref} aria-hidden="true">
      <Sheets c={c} keys={job.keys} logo={db.logo} exc={db.exc.filter((e) => e.ccrn === c.id)} />
    </div>
  );
}
